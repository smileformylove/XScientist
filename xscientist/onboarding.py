def _render_readme(
    *,
    profile: str,
    provider: str,
    model: str,
    task: str = "research",
    capabilities: tuple[str, ...] | None = None,
    provider_required: bool = True,
) -> str:
    image = f"xscientist-exec:{__version__}"
    install = _workspace_installation_command(
        provider=provider,
        capabilities=capabilities,
        provider_required=provider_required,
    )
    install_note = (
        f"This installs the selected capabilities and only the `{provider}` client."
        if provider_required
        else "This task is provider-neutral, so no model client is installed."
    )
    provider_note = (
        f"""```bash
xscientist provider check {provider}
# Optional, explicit one-request verification (may incur provider cost):
# xscientist provider check {provider} --live --json
# Only when the check reports missing configuration:
xscientist provider add {provider}
xscientist provider list
```

`setup` may already have completed this step. `provider add` reuses the model
`{model}` selected during setup and prompts for
missing secrets with hidden input. Existing process environment variables take
precedence and are never copied to disk implicitly."""
        if provider_required
        else "This task does not require an LLM provider. Add one later only when a selected task requests it."
    )
    workspace_summary = (
        f"provider `{provider}`, model `{model}`, and the packaged BFTS `{profile}` configuration"
        if provider_required
        else f"provider-neutral task `{task}` and the packaged BFTS `{profile}` compatibility template"
    )
