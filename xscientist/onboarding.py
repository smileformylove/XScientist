class WorkspaceInitError(ValueError):
    """Raised when a workspace cannot be created without surprising data loss."""


PROVIDER_ENV_LINES: dict[str, tuple[str, ...]] = {
    provider: tuple(
        f"{field.name}={field.default or 'replace-me'}"
        for field in fields
        if field.required or field.default is not None or provider == "vertex_ai"
    )
    for provider, fields in PROVIDER_FIELDS.items()
}

WORKSPACE_FILES = (
    ".dockerignore",
    ".env.example",
    ".gitignore",
    ".xscientist/providers.json",
    "Dockerfile.executor",
    "README.md",
    "bfts_config.yaml",
    "topic.md",
)


def _resolve_model(provider: str, model: str | None) -> str:
    try:
        _provider, selected = validate_provider_model(provider, model)
    except ProviderConfigError as exc:
        raise WorkspaceInitError(str(exc)) from exc
    return selected


def _render_bfts_config(profile: str, model: str) -> str:
    with bfts_config_path(profile).open("r", encoding="utf-8") as handle:
        payload = yaml.safe_load(handle)
    if not isinstance(payload, dict):
        raise WorkspaceInitError(f"packaged BFTS profile {profile!r} is invalid")

    image = f"xscientist-exec:{__version__}"
    exec_config = payload.setdefault("exec", {})
    exec_config["backend"] = "docker"
    exec_config["require_isolation"] = True
    exec_config["docker_image"] = image
    budget = payload.setdefault("llm_budget", {})
    budget["max_total_tokens"] = 2_000_000 if profile == "deep" else 500_000
    budget["max_wall_time_seconds"] = 86_400 if profile == "deep" else 21_600
    payload.setdefault("report", {})["model"] = model
    agent = payload.setdefault("agent", {})
    for key in ("code", "feedback", "vlm_feedback"):
        agent.setdefault(key, {})["model"] = model
    body = yaml.safe_dump(payload, sort_keys=False, allow_unicode=True)
    return f"# Generated by xscientist init from the {profile!r} profile.\n{body}"


def _render_env(provider: str) -> str:
    provider_lines = "\n".join(PROVIDER_ENV_LINES[provider])
    return (
        "# Example only. Prefer `xscientist provider add` for hidden API-key input.\n"
        "# A private .env created by that command is loaded inside this workspace.\n"
        "# Never commit .env.\n\n"
        "RESEARCH_OUTPUT_DIR=./outputs\n"
        f"{provider_lines}\n"
    )


def _installed_vcs_source() -> tuple[str, str] | None:
    """Return a safe PEP 610 VCS origin so executors install the exact commit."""

    try:
        raw = importlib_metadata.distribution("xscientist").read_text("direct_url.json")
        payload = json.loads(raw or "{}")
    except (importlib_metadata.PackageNotFoundError, json.JSONDecodeError, OSError):
        return None
    if not isinstance(payload, dict):
        return None
    vcs = payload.get("vcs_info")
    if not isinstance(vcs, dict) or vcs.get("vcs") != "git":
        return None
    commit = str(vcs.get("commit_id") or "").strip()
    url = str(payload.get("url") or "").strip().removeprefix("git+")
    if not re.fullmatch(r"[0-9a-fA-F]{7,64}", commit):
        return None
    parsed = urlsplit(url)
    if (
        parsed.scheme != "https"
        or not parsed.hostname
        or parsed.username
        or parsed.password
        or parsed.query
        or parsed.fragment
        or not re.fullmatch(r"[A-Za-z0-9._~:/@%+\-]+", url)
    ):
        return None
    return url, commit.lower()


def _workspace_installation_command(
    *,
    provider: str,
    capabilities: tuple[str, ...] | None,
    provider_required: bool,
) -> str:
    """Pin the host runtime to the same immutable source as the executor."""

    selected = capabilities if capabilities is not None else ("research",)
    package_spec = capability_installation_spec(
        selected,
        provider=provider if provider_required else None,
    )
    vcs_source = _installed_vcs_source()
    if vcs_source is not None:
        source_url, source_revision = vcs_source
        runtime_spec = f"{package_spec} @ git+{source_url}@{source_revision}"
    else:
        runtime_spec = capability_installation_spec(
            selected,
            provider=provider if provider_required else None,
            version=__version__,
        )
    return f'python -m pip install "{runtime_spec}"'


def _render_dockerfile(
    provider: str,
    *,
    capabilities: tuple[str, ...] | None = None,
    provider_required: bool = True,
) -> str:
    selected = capabilities if capabilities is not None else ("research",)
    package_spec = capability_installation_spec(
        selected,
        provider=provider if provider_required else None,
    )
    vcs_source = _installed_vcs_source()
    if vcs_source is None:
        runtime_spec = capability_installation_spec(
            selected,
            provider=provider if provider_required else None,
            version="${XSCIENTIST_VERSION}",
        )
        source_revision = "release"
        source_kind = "pypi-release"
    else:
        source_url, source_revision = vcs_source
        runtime_spec = f"{package_spec} @ git+{source_url}@{source_revision}"
        source_kind = "vcs-commit"
    local_extras = package_spec.removeprefix("xscientist")
    local_spec = f"/tmp/xscientist-build-context{local_extras}"
    torch_install = (
        "RUN python -m pip install --no-cache-dir \\\n    torch --index-url https://download.pytorch.org/whl/cpu\n"
        if "ml" in selected
        else ""
    )
    return f"""FROM python:3.11-slim

ARG XSCIENTIST_VERSION={__version__}
ARG XSCIENTIST_INSTALL_MODE=pypi
ARG XSCIENTIST_SOURCE_REVISION={source_revision}
ARG XSCIENTIST_INSTALL_SOURCE={source_kind}
ENV PIP_DISABLE_PIP_VERSION_CHECK=1 \\
    PYTHONDONTWRITEBYTECODE=1 \\
    PYTHONUNBUFFERED=1

RUN apt-get update \\
    && apt-get install -y --no-install-recommends build-essential git \\
    && rm -rf /var/lib/apt/lists/*
{torch_install}
COPY . /tmp/xscientist-build-context
RUN if [ "$XSCIENTIST_INSTALL_MODE" = "local" ]; then \\
      python -m pip install --no-cache-dir "{local_spec}"; \\
    else \\
      python -m pip install --no-cache-dir "{runtime_spec}"; \\
    fi \\
    && rm -rf /tmp/xscientist-build-context

LABEL org.opencontainers.image.version="$XSCIENTIST_VERSION" \\
      org.opencontainers.image.revision="$XSCIENTIST_SOURCE_REVISION" \\
      org.xscientist.install-source="$XSCIENTIST_INSTALL_SOURCE"

RUN useradd --create-home --uid 10001 scientist
USER scientist
WORKDIR /workspace

CMD ["python", "--version"]
"""


