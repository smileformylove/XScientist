class WorkspaceInitError(ValueError):
    """Raised when a workspace cannot be created without surprising data loss."""


def resolve_workspace_root(directory: str | Path) -> Path:
    """Resolve one workspace root without following any symlink component."""

    try:
        return resolve_provider_workspace_root(directory)
    except ProviderConfigError as exc:
        raise WorkspaceInitError(str(exc)) from exc


def _validate_persisted_config_value(label: str, value: object) -> str:
    """Reject private literals before rendering them into several managed files."""

    selected = str(value or "").strip()
    if selected and redact_sensitive_text(selected) != selected:
        raise WorkspaceInitError(
            f"{label} contains a credential or private literal; refusing to persist it"
        )
    return selected


PROVIDER_ENV_LINES: dict[str, tuple[str, ...]] = {
    provider: tuple(
        f"{field.name}={field.default or 'replace-me'}"
        for field in fields
        if field.required or field.default is not None or provider == "vertex_ai"
    )
    for provider, fields in PROVIDER_FIELDS.items()
}

